import numpy as np

#####################################################
# Step 1 : Define input features ie X
#####################################################

input = np.array([2.0, 3.0, 4.0])
print("X : ",input)

#####################################################
# Step 2 : Define weights ie w
#####################################################

weights = np.array([0.5, 0.3, 0.2])
print("W : ", weights)

#####################################################
# Step 3 : Define bias ie b
#####################################################

bias = 1.0
print("b : ",bias)

#####################################################
# Step 4 : Calculate Weighted sum ie z
#####################################################

# Z = x1w1 + x2w2 + x3w3 + b
# Z = (2.0 * 0.5) + (3.0 * 3.0) + (4.0 * 0.2) + 1.0

Z = np.dot(input, weights) + bias
print("Z : ",Z)

#####################################################
# Step 5 : Actiavation Function (ReLU)
#####################################################

def ReLU(x):
    return max(0, x)

#####################################################
# Step 6 : Final Output
#####################################################

Y = ReLU(Z)
print("Y : ",Y)